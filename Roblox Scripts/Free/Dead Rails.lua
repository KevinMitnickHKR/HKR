local function collectItems()
    local hrp = player.Character and player.Character:FindFirstChild("HumanoidRootPart")
    if not hrp then return end
    for _, item in pairs(workspace.RuntimeItems:GetChildren()) do
        if item:IsA("Model") then
            local shouldStore, shouldPickup, shouldCollect, shouldEquip = false, false, false, false
            if selectedCategories["General"] then
                shouldStore, shouldPickup, shouldCollect, shouldEquip = true, true, true, true
            else
                local itemCategories = getItemCategories_3(item)
                for category in pairs(itemCategories) do
                    if selectedCategories[category] then
                        local config = categoryCollectConfig[category] or {}
                        shouldStore = shouldStore or config[1]
                        shouldPickup = shouldPickup or config[2]
                        shouldCollect = shouldCollect or config[3]
                        shouldEquip = shouldEquip or config[4]
                    end
                end
            end
            if (hrp.Position - item:GetPivot().Position).Magnitude <= maxDistance then
                if shouldStore and hasSack() then
                    game:GetService("ReplicatedStorage").Remotes.StoreItem:FireServer(item)
                end
                if shouldPickup then
                    game:GetService("ReplicatedStorage").Remotes.Tool.PickUpTool:FireServer(item)
                end
                if shouldCollect then
                    game:GetService("ReplicatedStorage").Packages.RemotePromise.Remotes.C_ActivateObject:FireServer(item)
                end
                if shouldEquip then
                    game:GetService("ReplicatedStorage").Remotes.Object.EquipObject:FireServer(item)
                end
            end
        end
        if item.Name == "Moneybag" and item:FindFirstChild("MoneyBag") and selectedCategories["Valuable"] and (hrp.Position - item:GetPivot().Position).Magnitude <= maxDistance then
            local p = item.MoneyBag:FindFirstChild("CollectPrompt")
            if p then fireproximityprompt(p) end
        end
    end
end
