local function getClosestPhase()
    local LightingPresets = ReplicatedStorage:WaitForChild("Shared"):WaitForChild("DataBanks"):WaitForChild("LightingPresets")
    local currentHaze = Lighting:FindFirstChildOfClass("Atmosphere") and Lighting.Atmosphere.Haze or 0
    local currentAmbient = Lighting.Ambient
    local closestPhase, closestDifference = "Unknown", math.huge

    for _, preset in pairs(LightingPresets:GetChildren()) do
        local presetHaze = preset:FindFirstChild("Atmosphere") and preset.Atmosphere.Haze or 0
        local presetAmbient = preset:GetAttribute("Ambient")

        if presetAmbient then
            local diff = calculateDifference(currentHaze, presetHaze) +
                         calculateDifference(currentAmbient.R, presetAmbient.R) +
                         calculateDifference(currentAmbient.G, presetAmbient.G) +
                         calculateDifference(currentAmbient.B, presetAmbient.B)

            if diff < closestDifference then
                closestDifference = diff
                closestPhase = preset.Name
            end
        end
    end

    return closestPhase
end
