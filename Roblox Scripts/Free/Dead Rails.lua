                        if o:IsA("Model") and o:FindFirstChild("Configuration") then
                            local h = o:FindFirstChild(pTarget)
                            local hm = o:FindFirstChildOfClass("Humanoid")
                            if h and hm and hm.Health > 0 then
                                local distance = (h.Position - camPos).Magnitude
                                if distance <= maxDistance then
                                    local toTarget = (h.Position - camPos).unit
                                    local dot = camLook:Dot(toTarget)
                                    local score = (dot * 0.75) + ((1 - (distance / maxDistance)) * 0.25)
                                    if score > bestScore then
                                        bestScore = score
                                        bestTarget = h
                                    end
                                end
                            end
                        end
                    end
                    if bestTarget then
                        task.spawn(function()
                            local startTime = tick()
                            while tick() - startTime < 1.65 do
                                local hm = bestTarget.Parent and bestTarget.Parent:FindFirstChildOfClass("Humanoid")
                                if not hm or hm.Health <= 0 then break end
                                cam.CFrame = CFrame.lookAt(cam.CFrame.Position, bestTarget.Position)
                                task.wait()
                            end
                        end)
                    end
                end
