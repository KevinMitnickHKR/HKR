local function manageAutoHeal()
    if not conn and (bandageEnabled or snakeOilEnabled or autoEatEnabled) then
        conn = game:GetService("RunService").RenderStepped:Connect(function()
            local player = game.Players.LocalPlayer
            local character = player.Character
            if not character then return end
            local humanoid = character:FindFirstChildOfClass("Humanoid")
            if not humanoid or humanoid.Health > aBH then return end
            if tick() - lastUsed < cooldownTime then return end

            local backpack = player.Backpack
            local tools = {}
            for _, item in ipairs(character:GetChildren()) do
                if item:IsA("Tool") then
                    tools[#tools + 1] = item
                end
            end

            local usedItem = false

            if bandageEnabled and backpack:FindFirstChild("Bandage") then
                humanoid:EquipTool(backpack.Bandage)
                character.Bandage.Use:FireServer()
                usedItem = true
            end

            if snakeOilEnabled and backpack:FindFirstChild("Snake Oil") then
                humanoid:EquipTool(backpack["Snake Oil"])
                character["Snake Oil"].Use:FireServer(character:FindFirstChild("Snake Oil"))
                usedItem = true
            end

            if autoEatEnabled then
                for _, item in ipairs(workspace.RuntimeItems:GetChildren()) do
                    local eatPrompt = item:FindFirstChild("CorpseEatPrompt")
                    if eatPrompt then
                        eatPrompt.MaxActivationDistance = 9999
                        fireproximityprompt(eatPrompt)
                        usedItem = true
                        break
                    end
                end
            end

            if usedItem then
                lastUsed = tick()
                task.defer(function()
                    for _, tool in ipairs(tools) do
                        tool.Parent = character
                    end
                end)
            end
        end)
    elseif conn and not (bandageEnabled or snakeOilEnabled or autoEatEnabled) then
        conn:Disconnect()
        conn = nil
    end
end

